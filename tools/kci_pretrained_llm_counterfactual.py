"""Actual pretrained-LLM counterfactual continuations from a REAL Coordinator fork.

Reconstructs B preflight by replaying the prior LLM episode through native
transitions and validating its state hash. Forces one of two currently VALID
B actions. All subsequent learned decisions are generated by the frozen
local LLM, while common tool steps use the same native adapter as the CPU
reference. This is inference-only evidence for CCE, not LoRA training.
"""
from __future__ import annotations
from pathlib import Path
from dataclasses import asdict
import argparse,json,time,sys
ROOT=Path(__file__).resolve().parents[1]
sys.path[:0]=[str(ROOT/"code"),str(ROOT/"tools")]
from kci_pretrained_llm_native_runner import OllamaActor
from compare_kci_chain_methods_cpu_action_interaction import GROUP
from kci_exact_policy_continuation_cpu import environment_public
from chain_shared_actor_cpu_action_interaction import baseline_automatic_action,valid_decision_candidates
from kci.diverse_ci_branch_env import digest

def case_by_name(name):
    return next((row for rows in GROUP.values() for row in rows if row["world"]==name),None)

def replay_to_B(row,episode):
    e=environment_public(row)
    s=e.initial()
    target=next(x for x in episode["trace"] if x["phase"]=="preflight")
    for item in episode["trace"]:
        if item["phase"]=="preflight":break
        assert digest(asdict(s))==item["state_sha256_before"]
        s,a=e.transition(s,item["action"])
        assert a["verdict"] in ("VALID","VIOLATION")
    assert digest(asdict(s))==target["state_sha256_before"]
    assert s.native.done is False
    return e,s

def force_and_follow(e,start,action,model):
    st=start
    trace=[]
    before=digest(asdict(st))
    assert action in e.options(st)
    st,a=e.transition(st,action)
    assert a["verdict"]=="VALID"
    trace.append({"phase":"preflight","action":action,"from_fork":True,
                  "verdict":a["verdict"],"native_hash_before":before})
    calls=0
    for _ in range(60):
        if st.native.done:break
        obs=e.observation(st)
        candidates=valid_decision_candidates(obs,list(e.options(st)))
        if len(candidates)>1:
            try:
                nxt,raw,usage,phash=model.choose(obs)
            except Exception as exc:
                return {"terminal":"BACKEND_ERROR","error":str(exc)[:180],"trace":trace}
            calls+=1
            if nxt not in candidates:
                return {"terminal":"INVALID_ACTION","response":raw,"trace":trace}
            selected=nxt
        else:
            selected=baseline_automatic_action(e,st)
            raw=None;usage={}
        if not selected:return {"terminal":"NO_VALID_NATIVE_ADAPTER","trace":trace}
        old=digest(asdict(st))
        nxt,a=e.transition(st,selected)
        trace.append({"phase":obs.get("stage",obs.get("current_stage")),
                      "role":obs.get("actor",obs.get("role")),
                      "from_fork":False,"action":selected,"raw":raw,
                      "verdict":a["verdict"],"native_hash_before":old,
                      "new_R_receipts":len(nxt.native.delivered["R"])-len(st.native.delivered["R"]),
                      "usage":usage})
        if a["verdict"] not in ("VALID","VIOLATION"):
            return {"terminal":"UNVERIFIED_NATIVE_ACTION","trace":trace}
        st=nxt
    safe=st.native.done and st.native.success and not st.native.violation
    violation=bool(st.native.violation)
    return {"terminal":"DONE" if st.native.done else "STEP_CAP","safe_success":bool(safe),
            "CI_violation":violation,"reward":round(1-e.spec.cost_per_step*st.native.steps,6) if safe else(-1 if violation else 0),
            "final_steps":st.native.steps,"model_calls":calls,
            "trace":trace}

def main():
    parser=argparse.ArgumentParser()
    parser.add_argument("--name",required=True)
    parser.add_argument("--world-limit",type=int,default=4)
    parser.add_argument("--start",type=int,default=0)
    parser.add_argument("--model",default="qwen2.5:7b-instruct-q4_K_M")
    a=parser.parse_args()
    src=ROOT/"artifacts"/"20261122_kci_pretrained_llm_native"/"qwen7b_full_exploratory8_v1"/"EPISODES.jsonl"
    items=[json.loads(line) for line in src.read_text(encoding="utf8").splitlines()]
    out=ROOT/"artifacts"/"20261122_kci_pretrained_llm_native"/a.name
    if out.exists():raise FileExistsError(out)
    out.mkdir(parents=True)
    actor=OllamaActor(a.model)
    results=[]
    begin=time.monotonic()
    for episode in items[a.start:a.start+a.world_limit]:
        row=case_by_name(episode["world"])
        env,s=replay_to_B(row,episode)
        candidates=("OPEN_PRIVATE_CHANNEL","SKIP_PRIVATE_CHANNEL")
        vals={}
        for action in candidates:
            nxt,audit=env.transition(s,action)
            assert audit["verdict"]=="VALID"
            val=force_and_follow(env,s,action,actor)
            vals[action]=val
            print("NATIVE_LLM_FORK",episode["world"],action,
                  val.get("terminal"),val.get("reward"),
                  val.get("CI_violation"),
                  [(t["phase"],t["action"]) for t in val["trace"] if not t["from_fork"] and t["raw"] is not None],
                  "elapsed",round(time.monotonic()-begin,1),flush=True)
        results.append({"world":episode["world"],"A_choice":episode["A_choice"],
                        "fork_state_sha256":digest(asdict(s)),
                        "baseline_full_success":episode["safe_business_success"],
                        "baseline_full_violated":episode["CI_violation"],
                        "continuations":vals})
        with (out/"RESULTS.jsonl").open("a",encoding="utf8") as f:f.write(json.dumps(results[-1])+"\n")
    completed=[x for x in results if all(v.get("terminal")=="DONE" for v in x["continuations"].values())]
    summary={"type":"actual_LLM_native_CCE_fork",
             "model":a.model,"n_worlds":len(results),
             "valid_both_suffixes":len(completed),
             "open_success":sum(x["continuations"]["OPEN_PRIVATE_CHANNEL"].get("safe_success",False) for x in results),
             "skip_success":sum(x["continuations"]["SKIP_PRIVATE_CHANNEL"].get("safe_success",False) for x in results),
             "open_violations":sum(x["continuations"]["OPEN_PRIVATE_CHANNEL"].get("CI_violation",False) for x in results),
             "skip_violations":sum(x["continuations"]["SKIP_PRIVATE_CHANNEL"].get("CI_violation",False) for x in results),
             "elapsed":round(time.monotonic()-begin,2),"rollouts":len(results)*2,
             "test_seen_by_developers":True,"no_model_training":True}
    (out/"SUMMARY.json").write_text(json.dumps(summary,indent=2)+"\n",encoding="utf8")
    print("FINAL",json.dumps(summary),flush=True)
if __name__=="__main__":main()
